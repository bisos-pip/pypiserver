        pip and twine, and this host's pypiserver / pypi-browser systemd units.
        #+end_org """)

        literal = cs.examples.execInsert

        cs.examples.menuChapter('=Direct pypiserver Interface Commands=')

        cs.examples.menuSection('/Environment/')
        literal(f"export PIP_TRUSTED_HOST={pypiserverInfo.fqdn}   # pip ignores a plain-HTTP index otherwise")
        literal(f"export INDEX={pypiserverInfo.indexUrl}")
        literal(f"export TWINE_REPOSITORY_URL={pypiserverInfo.uploadUrl} TWINE_USERNAME={pypiserverInfo.adminUser} TWINE_PASSWORD={pypiserverInfo.adminPassword}")

        cs.examples.menuSection('/Download -- no login/')
        literal("pip install --extra-index-url $INDEX <package>")
        literal("pip index versions --index-url $INDEX <package>")

        cs.examples.menuSection('/Upload -- the login, from the environment above/')
        literal("python -m build                       # in a project: dist/*.whl and dist/*.tar.gz")
        literal(f"{pypiserverInfo.twineBin} upload dist/*")

        cs.examples.menuSection('/Index/')
        literal("curl -s $INDEX | head")
        literal(f"curl -s {pypiserverInfo.localUrl}/health")
        literal(f"{pypiserverInfo.venvBin('pypi-server')} --version")

        cs.examples.menuSection('/systemd Units/')
        literal("systemctl status pypiserver.service pypi-browser.service")
        literal("systemctl restart pypiserver.service pypi-browser.service")

        cs.examples.menuSection('/Logs -- journald only/')
        literal("journalctl -u pypiserver.service -f")
        literal("journalctl -u pypi-browser.service -f")

        cs.examples.menuChapter('=pypi-browser Hints=')

        cs.examples.menuSection('/Getting In/')
        literal(f"# {pypiserverInfo.baseUrl}   -- pypi-browser; no login (loopback-only behind nginx)")
        literal(f"# {pypiserverInfo.baseUrl}/package/<name>   -- a package's files; open one to browse inside it")

        cs.examples.menuSection('/Reading Failures/')
        literal("# Upload: 413 Request Entity Too Large -> client_max_body_size in pypiserver-wvd.pcs")
        literal("# Upload: 403                          -> the login; htpasswd in /etc/pypiserver")
        literal("# Upload: 409                          -> that version exists (pypiserver --overwrite allows it)")
        literal("# pip: 'not a trusted or secure host'  -> --trusted-host (or PIP_TRUSTED_HOST): the index is plain HTTP")
        literal("# pip: no matching distribution        -> not in this index; no fallback to PyPI (--extra-index-url)")

        return(cmndOutcome)


